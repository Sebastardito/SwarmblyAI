def _is_truncated(replica, budget: int | None) -> bool:
    """The generation stopped at its token budget rather than finishing.

    ``finish_reason == "length"`` when the worker reports it (app ≥ 0.2.1);
    otherwise output tokens at ≥ 98 % of the budget.
    """
    telemetry = getattr(replica, "telemetry", None) or {}
    reason = str(telemetry.get("finish_reason") or "")
    if reason:
        return reason == "length"
    tokens = telemetry.get("tokens_out")
    try:
        return bool(budget) and tokens is not None and int(tokens) >= 0.98 * int(budget)
    except (TypeError, ValueError):
        return False


LENGTH_TOLERANCE = 0.3


def _select_whole(replicas, meta, embedder, lang: str | None,
                  required: list[str] | None = None, target_words: int | None = None,
                  critical: list[str] | None = None):
    """Pick one complete replica: request language, then the names the
    section must carry (the presenter), then within ±30 % of the section's
    word target, then the other requirement words, then not truncated, then
    (outside the band) the closest length — tables have no word target —
    then the document medoid (highest mean cosine to the others).

    The length term (P3d.2, 22 Oct 2026): with the medoid alone the
    Galápagos speech came out 25 % short and the water-cycle article 29 %
    long, while a replica of the right length was available for most
    sections."""
    import numpy as np

    from ..lang import detect_language
    vectors = np.asarray(embedder.embed([r.text for r in replicas]), dtype=float)
    norms = np.linalg.norm(vectors, axis=1, keepdims=True)
    unit = vectors / np.where(norms == 0, 1.0, norms)
    sims = unit @ unit.T
    k = len(replicas)
    centrality = [(float(sims[i].sum() - sims[i, i]) / (k - 1)) for i in range(k)]
    langs = [detect_language(r.text) for r in replicas]
    lowered = [r.text.casefold() for r in replicas]
    met = [sum(1 for key in (required or []) if key in lowered[i]) for i in range(k)]
    words = [len(r.text.split()) for r in replicas]
    error = [abs(words[i] - target_words) / target_words if target_words else 0.0
             for i in range(k)]
    fits = [e <= LENGTH_TOLERANCE for e in error]
    # Within the band length is not a criterion; outside it the closer wins
    # (P3f.2: 195 and 83 words for a 144-word section, the 83 was chosen).
    names = [sum(1 for key in (critical or []) if key in lowered[i]) for i in range(k)]
    # Names first (the presenter), then length: counting the other required
    # words before length favoured the longest replica (P3g.2: 164 words
    # chosen over 73 for a 99-word section; the report came out +41 %).
    keys = [((langs[i] == lang) if lang else True, names[i], fits[i], met[i],
             not meta[i]["truncated"], -(0.0 if fits[i] else error[i]), centrality[i],
             -int(replicas[i].elapsed_ms or 0)) for i in range(k)]
    chosen = max(range(k), key=lambda i: keys[i])
    ranking = sorted(range(k), key=lambda i: keys[i], reverse=True)
    return chosen, {
        "ranking": ranking,
        "policy": ("whole replica: language match, then required names, then "
                   "length within ±30 % of the target, then requirement words, "
                   "then complete, then closest length, then document medoid"),
        "target_words": target_words,
        "chosen": chosen, "chosen_family": replicas[chosen].family,
        "candidates": [{"family": replicas[i].family, "language": langs[i],
                        "truncated": meta[i]["truncated"],
                        "requirements_met": met[i], "names_met": names[i],
                        "words": words[i],
                        "length_fits": fits[i],
                        "centrality": round(centrality[i], 4)} for i in range(k)],
    }


_ITEM_LINE = re.compile(r"^\s*[\[(]?(\d{1,3})[\]).:]\s+(.+?)\s*$", re.M)
_TABLE_ROW = re.compile(r"^\s*\|\s*\**(\d{1,3})\**\s*\|(.*?)\|?\s*$", re.M)
MAX_ITEM_ANSWER_WORDS = 4      # an answer on the line after its item is short
_LABEL_ANYWHERE = re.compile(r"(?:^|(?<=\s))[\[(]?(\d{1,3})[\]).:]\**\s+")
# A label left inside a value: "1. 7. libro" (renumbered from 1 with the
# original number kept, P3d.1) or "7.* Asunción".
_RESIDUAL_LABEL = re.compile(r"^[\[(]?\d{1,3}[\]).:]\**\s+")
_STRIP = " \t*_`#>\"'“”«»"


def _item_texts(instruction: str) -> dict[int, str]:
    """``{number: item text}`` for the numbered items of one fragment.

    The upstream planner appends its integration suffix to the last line of
    the last fragment ("8. 7000 m Close the answer; …"); workers never see it
    (``localise_instruction`` removes it), and neither does the item list
    (P3e.1, 22 Oct 2026: item 8 was shown with the English suffix)."""
    from .packets import UPSTREAM_INTEGRATION_SUFFIX
    text = instruction or ""
    if text.endswith(UPSTREAM_INTEGRATION_SUFFIX):
        text = text[: -len(UPSTREAM_INTEGRATION_SUFFIX)]
    return {int(m.group(1)): m.group(2) for m in _ITEM_LINE.finditer(text)}


def _parse_items(text: str, items: dict[int, str]) -> dict[int, str]:
    """A replica's answer per item: first occurrence of each wanted label.

    Values that only repeat the item's own text are not answers (a replica
    that re-lists its input); "Item: value", "Item – value" and "Item = value"
    keep the value. Items without a number label are found by a line that
    starts with the item's own text ("* 100 m = 0,1 km"), as small models
    often answer with bullets.
    """
    found: dict[int, str] = {}
    text = text or ""
    matches = list(_LABEL_ANYWHERE.finditer(text))
    for i, m in enumerate(matches):
        n = int(m.group(1))
        if n not in items or n in found:
            continue
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        lines = [ln for ln in text[m.end():end].split("\n")]
        value = _item_value(lines[0], items[n])
        if not value and len(lines) > 1:
            # "4. Iguana marina\n- reptil": the label repeats the item and the
            # answer is on the next line (qwen2.5:3b, P3h.1).
            nxt = next((ln for ln in lines[1:] if ln.strip(_STRIP + "-•")), "")
            bare = re.sub(r"^\s*[-*•]\s*", "", nxt).strip()
            short = len(bare.split()) <= MAX_ITEM_ANSWER_WORDS and not bare.endswith(":")
            value = _item_value(bare, items[n]) if nxt and short else ""
        if value:
            found[n] = value
    # Markdown table rows whose first cell is the item number:
    # "| 7 | Pingüino de Galápagos | Ave |" (P3l.1: a model answered the
    # whole batch as a table).
    for row in _TABLE_ROW.finditer(text):
        n = int(row.group(1))
        if n in items and n not in found:
            cells = [c.strip(_STRIP) for c in row.group(2).split("|")]
            cells = [c for c in cells if c and c.casefold() != items[n].strip(_STRIP).casefold()]
            if cells:
                found[n] = _item_value(cells[-1], items[n]) or cells[-1]
    missing = [n for n in items if n not in found]
    if missing:
        for line in text.splitlines():
            bare = re.sub(r"^\s*[-*•]\s*", "", line).strip(_STRIP)
            for n in missing:
                item = items[n].strip(_STRIP).rstrip(".;,")
                if n not in found and item and bare.casefold().startswith(item.casefold()):
                    value = _item_value(bare, items[n])
                    if value:
                        found[n] = value
    if not found and matches:
        # Renumbered from 1 ("1. large 2. small …" for items 19–24, P3c.1):
        # accepted only when the labels are exactly 1..k for k items.
        order = sorted(items)
        labels = [int(m.group(1)) for m in matches]
        # Only the first run 1..k counts: a model that repeats its answer in a
        # code fence ("1. Ave 2. Anfibio ```markdown 1. Ave 2. Anfibio```")
        # restarts the numbering (P3j.1).
        run = 0
        while run < len(labels) and labels[run] == run + 1:
            run += 1
        if run == len(order):
            for i, m in enumerate(matches[:run]):
                end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
                value = _item_value(text[m.end():end].split("\n")[0], items[order[i]])
                if value:
                    found[order[i]] = value
    if not found and not matches:
        # No labels at all, one answer per line in item order ("Reptil\nAve\nPez"):
        # accepted only when the line count matches the item count exactly
        # (P3c.1, 22 Oct 2026: correct answers rejected for lacking numbers).
        lines = [re.sub(r"^\s*[-*•]\s*", "", ln).strip(_STRIP).rstrip(".;,")
                 for ln in text.split("```")[0 if not text.lstrip().startswith("```") else 1]
                 .splitlines()]
        lines = [ln for ln in lines if ln and ln.lower() not in ("markdown", "md", "text")
                 and not ln.endswith(":")]
        if len(lines) == len(items):
            for n, line in zip(sorted(items), lines):
                value = _item_value(line, items[n])
                if value:
                    found[n] = value
    return found


_SEPARATOR = re.compile(r"\s[:–—=→-]\s|:\s")


def _item_value(raw: str, item_text: str) -> str:
    value = re.sub(r"\*\*|__", "", raw.split("```")[0])     # "**12.5** km" (P3j.1)
    value = value.strip(_STRIP).rstrip(".;,").strip(_STRIP)
    value = _RESIDUAL_LABEL.sub("", value).strip(_STRIP)
    item = item_text.strip(_STRIP).rstrip(".;,")
    if value.casefold().startswith(item.casefold()):
        value = value[len(item):].lstrip(" :-–—=→*_`\"'").strip(_STRIP)
    elif _SEPARATOR.search(value):
        value = _SEPARATOR.split(value)[-1].strip(_STRIP)
    value = value.rstrip(".;,").strip()
    return value if value and value.casefold() != item.casefold() else ""


class _ItemCheck:
    """Quality check of a batch replica: at least half its items answered.
    ``explain`` goes into the rejected attempt's note (P3f: a correct-looking
    replica was rejected and the reason could not be reconstructed)."""

    def __init__(self, items: dict[int, str]):
        self.items = items
        self.need = max(1, -(-len(items) // 2))

    def __call__(self, text: str) -> bool:
        return len(_parse_items(text, self.items)) >= self.need

    def explain(self, text: str) -> str:
        parsed = _parse_items(text, self.items)
        out = (f"items {min(self.items)}-{max(self.items)}: read "
               f"{sorted(parsed) or 'none'}, need {self.need}")
        if not parsed:
            # Hidden characters do not survive the whitespace-collapsed
            # preview (P3h.1: "1. 5. sol - sun …" read as nothing).
            out += f"; raw {ascii((text or '')[:48])}"
        return out


def _with_block(instruction: str, block: str) -> str:
    """The fragment's items, then an evidence block (before the directive
    that ``localise_instruction`` appends)."""
    if not block:
        return instruction
    from .packets import UPSTREAM_INTEGRATION_SUFFIX
    text = instruction
    if text.endswith(UPSTREAM_INTEGRATION_SUFFIX):
        text = text[: -len(UPSTREAM_INTEGRATION_SUFFIX)]
    return f"{text.rstrip()}\n\n{block}"


def _no_answer(n: int, item: str, lang: str | None) -> str:
    from ..lang import strings
    return f"{n}. {item.strip(_STRIP)} — {strings(lang)['no_answer']}"


def _normalise_items(text: str, items: dict[int, str], lang: str | None = None,
                     rejected: bool = False) -> str:
    """One ``n. value`` line per item, when at least half parse; an item
    without an answer is marked as such, never invented. Below half, the text
    as given (an answer in prose, "Todas son aves."), unless the replica
    failed the quality check: its raw text is not shown (P3d.1: an echoed
    list and "En formato markdown, esto se vería así: ```" reached the
    answer)."""
    parsed = _parse_items(text, items)
    if len(parsed) * 2 < len(items) and not rejected:
        return text
    return "\n".join(f"{n}. {parsed[n]}" if n in parsed else _no_answer(n, items[n], lang)
                     for n in sorted(items))


_NUMBER = re.compile(r"\s*(-?\d+(?:[.,]\d+)?)(?!\d)")


def _vote_key(value: str) -> str:
    """What two answers must share to count as the same vote.

    Numbers compare by value ("1.5" = "1.5 km" = "1,5"; after "=" the result
    is taken), and a one-word answer by its singular ("Aves" = "ave"): in
    P3h.1 every fragment of the length batch went to a tie-break over units
    alone.
    """
    text = value.casefold()
    if "=" in text:
        text = text.rsplit("=", 1)[1]
    number = _NUMBER.match(text)
    if number:
        return "#" + format(float(number.group(1).replace(",", ".")), "g")
    key = re.sub(r"[^\w]+", " ", text).strip()
    if " " not in key and len(key) > 3:
        if key.endswith("es") and key[-3] in "lrnd":
            key = key[:-2]
        elif key.endswith("s"):
            key = key[:-1]
    return key


def _split_items(replicas, items: dict[int, str]) -> list[int]:
    """Items that two replicas both answer, differently."""
    a, b = (_parse_items(r.text, items) for r in replicas[:2])
    return [n for n in sorted(items)
            if n in a and n in b and _vote_key(a[n]) != _vote_key(b[n])]


def _vote_items(replicas, items: dict[int, str], ranking: list[int],
                lang: str | None = None):
    """Majority vote per numbered item; ``None`` when replicas are unparseable."""
    parsed = [_parse_items(r.text, items) for r in replicas]
    if sum(len(p) for p in parsed) < 0.5 * len(items) * len(replicas):
        return None
    rank = {idx: pos for pos, idx in enumerate(ranking)}
    # Answers read by position carry no item numbers; a model that reorders
    # them ("6. Pez / 5. Aves / 4. Reptil" without the numbers) would map
    # them to the wrong items (P3g.1). In a tie they lose to labelled ones.
    labelled = [_LABEL_ANYWHERE.search(r.text or "") is not None for r in replicas]
    lines, report, missing = [], [], []
    for n in sorted(items):
        votes: dict[str, list[int]] = {}
        for idx, answers in enumerate(parsed):
            if n in answers:
                votes.setdefault(_vote_key(answers[n]), []).append(idx)
        if not votes:
            missing.append(n)
            lines.append(_no_answer(n, items[n], lang))
            continue
        best = max(votes.values(), key=lambda idxs: (len(idxs),
                                                     sum(labelled[i] for i in idxs),
                                                     -min(rank[i] for i in idxs)))
        winner = min(best, key=lambda i: (not labelled[i], rank[i]))
        value = parsed[winner][n]
        lines.append(f"{n}. {value}")
        report.append({"item": n, "value": value,
                       "agreement": round(len(best) / len(replicas), 4),
                       "distinct_answers": len(votes)})
    return "\n".join(lines), {
        "policy": "item vote: majority per numbered item, ties to numbered answers, "
                  "then to the best-ranked replica (language, complete, document "
                  "medoid)",
        "items": report, "missing_items": missing,
        "mean_item_agreement": (round(sum(r["agreement"] for r in report) / len(report), 4)
                                if report else None),
    }


def _order(task_id: str) -> int:
    digits = "".join(ch for ch in task_id if ch.isdigit())
    return int(digits) if digits else 0


def _topological_levels(plan) -> list[set[str]]:
    return _topological_levels_from({t.task_id: tuple(t.depends_on) for t in plan.tasks})


def _topological_levels_from(deps: dict[str, tuple[str, ...]]) -> list[set[str]]:
    remaining = {tid: set(d) for tid, d in deps.items()}
    levels: list[set[str]] = []
    while remaining:
        level = {tid for tid, d in remaining.items() if not d}
        if not level:
            raise ValueError("plan has a cycle")
        levels.append(level)
        remaining = {tid: d - level for tid, d in remaining.items() if tid not in level}
    return levels
