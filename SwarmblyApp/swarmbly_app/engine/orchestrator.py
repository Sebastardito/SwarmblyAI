    @staticmethod
    def _validators(plan, path, outline) -> dict[str, Any]:
        """Content checks per task (scheduler ``validate``): a replica that
        fails is retried on another node, within ``k_max``."""
        out: dict[str, Any] = {}
        if path == "enumerated":
            for t in plan.tasks:
                items = _item_texts(t.instruction)
                if items:
                    out[t.task_id] = _ItemCheck(items)
        elif outline is not None:
            for i, sec in enumerate(outline.sections):
                if sec.kind == "table":
                    # A table section without a table is not usable (P3j.2:
                    # the water-cycle article came out with no table at all).
                    out[f"t{i}"] = lambda text: len(re.findall(
                        r"^\s*\|.*\|\s*$", text or "", re.M)) >= 3
                    continue
                floor = max(15, int(sec.words * 0.25))
                out[f"t{i}"] = lambda text, floor=floor: len((text or "").split()) >= floor
        return out

    @staticmethod
    def _assemble_composition(plan, outline, resolved, embedder):
        """Sections in outline order under the title; seams measured, never bridged."""
        import numpy as np
        texts = [composer.clean_section(resolved[t.task_id]["text"], outline.sections[i],
                                        outline.title)
                 for i, t in enumerate(plan.tasks) if t.task_id in resolved]
        seams = []
        if len(texts) >= 2:
            tails = [" ".join(t.split()[-60:]) for t in texts]
            heads = [" ".join(t.split()[:60]) for t in texts]
            vecs = np.asarray(embedder.embed(tails[:-1] + heads[1:]), dtype=float)
            norms = np.linalg.norm(vecs, axis=1, keepdims=True)
            unit = vecs / np.where(norms == 0, 1.0, norms)
            k = len(texts) - 1
            for i in range(k):
                seams.append({"left": plan.tasks[i].task_id, "right": plan.tasks[i + 1].task_id,
                              "similarity": round(float(unit[i] @ unit[k + i]), 4),
                              "path": "splice"})
        return (composer.assemble(outline, texts), seams,
                "composition: ordered sections; transitions written by the workers "
                "(no bridges)")

