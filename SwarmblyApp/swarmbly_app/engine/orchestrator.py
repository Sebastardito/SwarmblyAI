    def _clamp(self, max_tokens: int, workers: list[Any] | None = None) -> int:
        """Never ask more than the smallest worker policy allows (SPEC §12).

        ``workers`` are the peers this request may use (the local pool has no
        per-task limit); by default, every connected remote worker.
        """
        limits = []
        peers = workers if workers is not None else self.nodes.available_workers()
        for peer in peers:
            try:
                limit = int((peer.advertisement.get("policy") or {})
                            .get("max_tokens_per_task") or 0)
            except (TypeError, ValueError):
                limit = 0
            if limit:
                limits.append(limit)
        return min([max_tokens] + limits)

    @staticmethod
    def _budget(model_cfg: dict[str, Any], request, n_tasks: int, whole: bool) -> int:
        """Output tokens to ask of each task, from the length the user asked for.

        A fixed 400 tokens per fragment truncated a requested 800-word essay
        (diagnosis 2026-10-15, finding 3b). Whole-request replicas get the
        model's full ``max_tokens``; fragments get the configured fragment
        budget. Either way, an explicit length raises the budget to
        ``1.5 × target / n_tasks`` (headroom for the language's token rate).
        """
        full = int(model_cfg.get("max_tokens", 1024))
        base = full if whole else int(model_cfg.get("max_tokens_per_fragment",
                                                    min(400, full)))
        if request.length_explicit:
            needed = int(LENGTH_HEADROOM * request.contract.target_length_tokens
                         / max(1, 1 if whole else n_tasks)) + 1
            base = max(base, needed)
        return max(16, min(base, MAX_BUDGET_TOKENS))

    def _embedder(self):
        """Seam/agreement similarity: the ``embeddings`` role, else the old switch.

        Generated fragments can quote the user's passages, so a role on a
        third-party server follows the same two authorisations as retrieval
        (and refuses before sending).  With no role configured the previous
        behaviour is kept exactly: ``model.embedder=hash`` is lexical, and
        ``server`` uses ``/v1/embeddings`` at ``model.backend_url``.
        """
        model_cfg = self.config()["model"]
        from .. import roles
        if roles.embeddings_configured(self.config()):
            choice = roles.choose("embeddings", self.config(), None, "",
                                  passages=True)
            if choice.backend is not None:
                from ..inference.embeddings import DocumentEmbedder
                from swarmbly_v0 import HashEmbedder
                suffix = " (fallback: local)" if choice.note else ""
                return (DocumentEmbedder(choice.backend, HashEmbedder()),
                        f"server:{choice.model}{suffix}")
            from swarmbly_v0 import HashEmbedder
            note = choice.note or "no embeddings backend"
            return HashEmbedder(), f"hash (lexical, not semantic; {note})"
        if model_cfg.get("embedder") == "server":
            try:
                from swarmbly_v0 import HashEmbedder
                from ..inference.embeddings import DocumentEmbedder, openai_embedder
                model = str(model_cfg.get("embed_model") or "nomic-embed-text")
                client = openai_embedder(
                    model, str(model_cfg.get("backend_url") or "http://127.0.0.1:11434"),
                    api_key=str(model_cfg.get("api_key") or "not-needed"))
                return DocumentEmbedder(client, HashEmbedder()), "server:" + model
            except Exception:
                pass
        from swarmbly_v0 import HashEmbedder
        return HashEmbedder(), "hash (lexical, not semantic)"

