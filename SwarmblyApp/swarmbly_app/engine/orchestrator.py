class Cancelled(RuntimeError):
    pass


@dataclass
class Stage:
    name: str
    status: str = "pending"
    detail: dict[str, Any] = field(default_factory=dict)
    started: float | None = None
    elapsed_ms: int | None = None

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {"stage": self.name, "status": self.status}
        out.update(self.detail)
        if self.elapsed_ms is not None:
            out["elapsed_ms"] = self.elapsed_ms
        return out


class StageTracker:
    def __init__(self, bus: EventBus, request_id: str):
        self.bus = bus
        self.request_id = request_id
        self.stages = {name: Stage(name) for name in PIPELINE_STAGES}

    def _emit(self, stage: Stage) -> None:
        self.bus.publish("request.stage", request_id=self.request_id,
                         **stage.to_dict())

    def start(self, name: str, **detail: Any) -> None:
        stage = self.stages[name]
        stage.status, stage.started = "running", time.monotonic()
        stage.detail.update(detail)
        self._emit(stage)

    def _end(self, name: str, status: str, detail: dict[str, Any]) -> None:
        stage = self.stages[name]
        if stage.started is not None:
            stage.elapsed_ms = int((time.monotonic() - stage.started) * 1000)
        stage.status = status
        stage.detail.update(detail)
        self._emit(stage)

    def complete(self, name: str, **detail: Any) -> None:
        self._end(name, "completed", detail)

    def partial(self, name: str, **detail: Any) -> None:
        self._end(name, "partial", detail)

    def skip(self, name: str, reason: str) -> None:
        self._end(name, "skipped", {"reason": reason})

    def fail(self, name: str, detail: str) -> None:
        self._end(name, "failed", {"detail": detail})

    def skip_rest(self, names: list[str], reason: str) -> None:
        for name in names:
            if self.stages[name].status == "pending":
                self.skip(name, reason)

    def list(self) -> list[dict[str, Any]]:
        return [s.to_dict() for s in self.stages.values()]

    def timings(self) -> dict[str, int]:
        return {s.name: s.elapsed_ms for s in self.stages.values()
                if s.elapsed_ms is not None}


class LocalPromptBackend:
    """``generate(prompt)`` on the local model, for transition bridges (SPEC
    §14.3: bridges are generated by the local model). A failing local model
    never aborts assembly: the seam is spliced and the failure recorded."""

    def __init__(self, stream: StreamBackend | None, model: str):
        self._stream = stream
        self.model = model
        self.failures = 0
        self.calls = 0

    def generate(self, prompt: str, **kw: Any) -> str:
        self.calls += 1
        if self._stream is None or not self.model:
            self.failures += 1
            return ""
        try:
            return self._stream.stream_chat(
                [{"role": "user", "content": prompt}], model=self.model,
                max_tokens=int(kw.get("max_tokens", 120)),
                temperature=float(kw.get("temperature", 0.2))).text
        except Exception:
            self.failures += 1
            return ""


class Orchestrator:
    def __init__(self, nodes: NodeManager, bus: EventBus,
                 local_stream: StreamBackend | None,
                 config_getter: Callable[[], dict[str, Any]],
                 local_model: str = "", latency: LatencyStats | None = None,
                 stats_sink: Callable[..., None] | None = None,
                 local_pool_factory: Callable[[], Any] | None = None,
                 speed: Any = None, role_stats: Any = None,
                 public_query: Callable[[str, str], str] | None = None,
                 credits: Any = None):
        self.nodes = nodes
        self.bus = bus
        self.local_stream = local_stream
        self.config = config_getter
        self.local_model = local_model
        self.latency = latency or LatencyStats()
        from .scheduler import SpeedStats
        # learned per (node, model); the app keeps one across orchestrator rebuilds
        self.speed = speed or SpeedStats()
        # 3.5, D-018: learned per (node, role), kept the same way.
        from .scheduler import RoleStats
        self.role_stats = role_stats or RoleStats()
        # WP4b: the requester's public-query guard (AppState owns the settings,
        # glossary and private terms). A missing callback falls back to the
        # same guard with no glossary.
        self.public_query = public_query
        self.stats_sink = stats_sink
        self.local_pool_factory = local_pool_factory
        # 3.5, D-020: receipts are issued on acceptance, never before.
        self.credits = credits

    # -- public entry -----------------------------------------------------------
    def run(self, text: str, *, mode: str = "lan", request_id: str | None = None,
            cancel: threading.Event | None = None,
            history: list[dict[str, Any]] | None = None,
            passage_texts: list[str] | None = None,
            passage_peer_ids: set[str] | None = None,
            task_roles: dict[str, str] | None = None,
            team: Any = None,
            project_id: str = "") -> dict[str, Any]:
        """Execute one request. Returns ``routed`` = distributed | local | error.

        ``history`` is the conversation before ``text`` (role/content dicts).
        It never leaves the device: a follow-up is rewritten locally into a
        self-contained request (``followup.py``), and only that is planned.
        """
        request_id = request_id or uuid.uuid4().hex[:16]
        cfg = self.config()
        swarm_cfg, privacy_cfg = cfg["swarm"], cfg["privacy"]
        tracker = StageTracker(self.bus, request_id)
        started = time.time()

        def local(reason: str, **meta: Any) -> dict[str, Any]:
            tracker.skip_rest(DISTRIBUTED_ONLY, reason)
            tracker.skip("FINAL RESPONSE", "answered by the local model")
            return {"routed": "local", "reason": reason,
                    "metadata": {"routing_decision": reason, **meta},
                    "stages": tracker.list()}

        tracker.start("REQUEST RECEIVED")
        rewritten, rewrite_source = standalone(
            text, history, LocalPromptBackend(self.local_stream, self.local_model))
        if rewritten is None:
            tracker.complete("REQUEST RECEIVED", mode=mode, standalone=rewrite_source)
            tracker.skip_rest(["PRIVACY CLASSIFICATION", "ROUTING / DECOMPOSABILITY"],
                              "follow-up answered with the conversation")
            return local("this message refers to earlier turns and no local model could "
                         "rewrite it as a self-contained request; answered locally with "
                         "the conversation", standalone=rewrite_source)
        rewritten_view = ({"standalone_request": rewritten[:300]}
                          if rewrite_source == "local_rewrite" else {})
        text = rewritten
        tracker.complete("REQUEST RECEIVED", mode=mode, standalone=rewrite_source,
                         **rewritten_view)

        # 1. Privacy: tier (SPEC §15c) and lane (SPEC §15), both on-device.
        tracker.start("PRIVACY CLASSIFICATION")
        decision = self._classify(text, privacy_cfg)
        lane = self._lane(text)
        routing_meta = {"tier": decision["tier"], "swarm_id": None,
                        "classifier": decision["source"], "mtls": False,
                        "lane": lane, "standalone": rewrite_source}
        tracker.complete("PRIVACY CLASSIFICATION", tier=decision["tier"],
                         lane=lane, source=decision["source"],
                         rationale=decision["rationale"],
                         note="automatic triage raises a tier; it never "
                              "certifies the absence of sensitive content")
        # Where may this request go? Remote peers only for GLOBAL + PUBLIC in a
        # swarm mode; the local multi-model pool at any tier (nothing leaves).
        egress_block = ""
        if decision["tier"] == "LOCAL":
            egress_block = "privacy tier LOCAL: nothing leaves the device"
        elif decision["tier"] == "TRUSTED":
            egress_block = ("tier TRUSTED requires mutual TLS (not implemented): "
                            "nothing is sent")
        elif lane == "SENSITIVE":
            egress_block = "content classified SENSITIVE: local execution only (no TEE workers)"
        elif lane == "SANITISABLE":
            egress_block = ("content classified SANITISABLE: pseudonymisation is not "
                            "implemented yet, so it stays local")
        elif mode not in ("lan", "auto"):
            egress_block = f"mode {mode}: no network dispatch"
        pool = self.local_pool_factory() if self.local_pool_factory else None
        if not egress_block and mode in ("lan", "auto"):
            # 3.5, WP3 / D-016: a circle relay lets a member that is not on
            # this LAN become visible to placement. Direct paths are still
            # tried first inside ensure_peer; a relay failure is swallowed.
            try:
                self.nodes.ensure_circle_peers()
            except Exception:
                pass
        directory = Directory(self.nodes, pool, remote_allowed=not egress_block,
                              allowed_remote=passage_peer_ids)
        routing_meta["remote_allowed"] = not egress_block
        if passage_peer_ids is not None:
            routing_meta["passage_peer_filter"] = sorted(passage_peer_ids)
        routing_meta["local_pool"] = pool.models if pool else []
        if egress_block and pool is None:
            tracker.skip("ROUTING / DECOMPOSABILITY", egress_block)
            return local(egress_block, routing=routing_meta)

        # 2. A team is an explicit, stored plan: it replaces the router and the
        # planner, never the gates above or below (D-019). The same template
        # therefore runs on one node or several, by role.
        if team is not None:
            tracker.start("ROUTING / DECOMPOSABILITY")
            workers = directory.available_workers()
            adm = admission_mod.Admission(
                True, "team", "stored plan template", text,
                len(team.get("steps") or []))
            tracker.complete("ROUTING / DECOMPOSABILITY",
                             decomposable=False, admission=adm.to_dict(),
                             path=f"team: {team.get('name') or team.get('id') or ''}",
                             remote_allowed=not egress_block,
                             local_pool=len(pool.models) if pool else 0,
                             notes="a stored plan template replaces the router "
                                   "and the planner; privacy, admission, egress, "
                                   "passage and role rules are unchanged")
            router_meta = {"decomposable": False, "team": {
                "id": team.get("id") or "", "name": team.get("name") or "",
                "steps": len(team.get("steps") or [])},
                "admission": adm.to_dict()}
            if not workers:
                return local(egress_block or "no connected worker is available",
                             routing=routing_meta, router=router_meta)
            try:
                return self._distributed(text, adm, decision, lane, routing_meta,
                                         router_meta, directory, tracker, request_id,
                                         started, cancel, mode, False, False,
                                         passage_texts=passage_texts,
                                         task_roles=task_roles, team=team,
                                         project_id=project_id)
            except Cancelled:
                tracker.fail("FINAL RESPONSE", "interrupted by the user")
                return {"routed": "error", "reason": "interrupted by the user",
                        "metadata": {"routing": routing_meta},
                        "stages": tracker.list(), "status": "stopped"}
            except Exception as exc:
                for name in PIPELINE_STAGES:
                    if tracker.stages[name].status == "running":
                        tracker.fail(name, str(exc)[:200])
                tracker.skip_rest(PIPELINE_STAGES, "not reached")
                if tracker.stages["FINAL RESPONSE"].status != "failed":
                    tracker.fail("FINAL RESPONSE", str(exc)[:200])
                return {"routed": "error",
                        "reason": f"team execution failed: {exc}",
                        "metadata": {"routing": routing_meta, "router": router_meta},
                        "stages": tracker.list()}

        # 2. Router + plan admission.
        tracker.start("ROUTING / DECOMPOSABILITY")
        routing = self._route(text)
        workers = directory.available_workers()
        adm = admission_mod.admit(
            text, n_max=int(swarm_cfg.get("n_fragments_max", 4)),
            n_workers=directory.capacity(),
            min_items_per_fragment=int(swarm_cfg.get("min_items_per_fragment", 3)))
        k_min = max(1, int(swarm_cfg.get("k_min", 1)))
        whole = False
        compose = self._composer_applies(text, adm, swarm_cfg, workers)
        if compose:
            pass  # P1: the local model plans sections; workers write them
        elif not (routing.decomposable and adm.admitted) and pool is not None and k_min >= 2:
            # Not fragmentable, but several local families can each answer the
            # whole request and be aligned (SPEC §14b: replicas of one task;
            # nothing is split). Local pool only: the full request never travels.
            whole = True
            directory = Directory(None, pool, remote_allowed=False)
        tracker.complete("ROUTING / DECOMPOSABILITY",
                         decomposable=bool(routing.decomposable),
                         score=round(float(routing.score), 4),
                         threshold=round(float(routing.threshold), 4),
                         threshold_source="swarmbly_v0 default (uncalibrated)",
                         admission=adm.to_dict(),
                         path=("composition: sections planned by the local model"
                               if compose else
                               "whole-request replicas on local models" if whole
                               else "fragments"),
                         remote_allowed=not egress_block,
                         local_pool=len(pool.models) if pool else 0)
        router_meta = {"decomposable": bool(routing.decomposable),
                       "score": round(float(routing.score), 4),
                       "admission": adm.to_dict(), "whole_request_replicas": whole,
                       "composition": compose}
        if not whole and not compose:
            if not routing.decomposable:
                return local("the router judged the request not decomposable",
                             routing=routing_meta, router=router_meta)
            if not adm.admitted:
                return local(f"not fragmented: {adm.reason}", routing=routing_meta,
                             router=router_meta)
        if not workers:
            return local(egress_block or "no connected worker is available",
                         routing=routing_meta, router=router_meta)

        try:
            return self._distributed(text, adm, decision, lane, routing_meta,
                                     router_meta, directory, tracker, request_id,
                                     started, cancel, mode, whole, compose,
                                     passage_texts=passage_texts,
                                     task_roles=task_roles,
                                     project_id=project_id)
        except Cancelled:
            tracker.fail("FINAL RESPONSE", "interrupted by the user")
            return {"routed": "error", "reason": "interrupted by the user",
                    "metadata": {"routing": routing_meta}, "stages": tracker.list(),
                    "status": "stopped"}
        except Exception as exc:
            for name in PIPELINE_STAGES:
                if tracker.stages[name].status == "running":
                    tracker.fail(name, str(exc)[:200])
            tracker.skip_rest(PIPELINE_STAGES, "not reached")
            if tracker.stages["FINAL RESPONSE"].status != "failed":
                tracker.fail("FINAL RESPONSE", str(exc)[:200])
            return {"routed": "error", "reason": f"distributed execution failed: {exc}",
                    "metadata": {"routing": routing_meta, "router": router_meta},
                    "stages": tracker.list()}

    # -- the distributed path --------------------------------------------------------
    def _distributed(self, text, adm, decision, lane, routing_meta, router_meta,
                     directory, tracker, request_id, started, cancel, mode, whole=False,
                     compose=False, passage_texts=None, task_roles=None, team=None,
                     project_id=""):
        from swarmbly_v0 import planner
        from swarmbly_v0.schema import Plan, Task
        cfg = self.config()
        swarm_cfg = cfg["swarm"]
        workers = directory.available_workers()

        tracker.start("TASK PLANNING")
        path = "composition" if compose else "whole" if whole else adm.path
        request = build_contract(text if (whole or compose or team is not None)
                                 else adm.prompt)
        contract, lang = request.contract, request.lang
        outline = None
        team_labels: dict[str, str] = {}
        team_meta = None
        if team is not None:
            plan, task_roles, team_labels = self._team_plan(team, text)
            path = "team"
            consumed = {t.task_id: tuple(t.depends_on) for t in plan.tasks}
            levels = _topological_levels(plan)
            team_meta = {"id": team.get("id") or "",
                         "name": team.get("name") or "",
                         "builtin": bool(team.get("builtin")),
                         "steps": len(plan.tasks)}
        elif compose:
            outline = composer.make_outline(
                text, contract, lang, int(request.target_words or 0),
                LocalPromptBackend(self.local_stream, self.local_model),
                int(swarm_cfg.get("composer_max_sections", 6)))
            plan = Plan(prompt=text, tasks=[
                Task(task_id=f"t{i}",
                     instruction=composer.section_instruction(
                         outline, i, lang,
                         float(swarm_cfg.get("composer_length_factor", 0.8))),
                     kind="section") for i in range(len(outline.sections))])
        elif whole:
            plan = Plan(prompt=text, tasks=[Task(task_id="t0", instruction=text)])
        else:
            # answer_sheet=False: the user's own closing instructions (format,
            # presenter, tables…) travel with every fragment. The upstream
            # answer-sheet mode replaced them with an English "[NN] value"
            # directive (diagnosis 2026-10-15, finding 2).
            plan = planner.plan(adm.prompt, backend=None, n_tasks=adm.n_tasks,
                                contract=contract, force_sequential=False,
                                answer_sheet=False)
            if plan.sequential or len(plan.tasks) < 2:
                raise RuntimeError("the plan is a chain or a single task (SPEC §7)")
        if team is None:
            levels = _topological_levels(plan)
            consumed = {t.task_id: (t.depends_on
                                    if planner.consumes_predecessor(t.instruction)
                                    else ()) for t in plan.tasks}
        tracker.complete("TASK PLANNING", n_tasks=len(plan.tasks),
                         n_levels=len(levels), language=lang,
                         target_words=request.target_words,
                         **({"outline_source": outline.source,
                             "outline_errors": outline.errors,
                             "sections": [s.heading for s in outline.sections]}
                            if outline else {}),
                         **({"team": team_meta} if team_meta else {}),
                         path=("team: stored plan template" if team is not None else
                               "composition (sections)" if compose else
                               "whole request (replicas)" if whole else adm.path),
                         dispatch_waves=len(_topological_levels_from(consumed)),
                         edges_statement=sum(1 for t in plan.tasks
                                             if t.depends_on and not consumed[t.task_id]))

        tracker.start("PACKET GENERATION")
        session_id = new_session_id()
        positions: dict[str, tuple[int, int]] = {}
        for level_no, level in enumerate(levels):
            for index, task_id in enumerate(sorted(level, key=_order)):
                positions[task_id] = (level_no, index)
        max_tokens = self._budget(cfg["model"], request, len(plan.tasks), whole)
        budgets = {t.task_id: max_tokens for t in plan.tasks}
        if outline is not None:
            rate = _TOKENS_PER_WORD.get(lang, 1.3)
            budgets = {f"t{i}": composer.section_budget(sec, rate)
                       for i, sec in enumerate(outline.sections)}
            max_tokens = max(budgets.values())
        objective = minimal_objective(adm, contract)
        if outline is not None:
            # The request's first sentence states the length of the WHOLE text
            # ("800 words"); a section must not read it as its own target.
            objective = (outline.title or outline.topic or objective)[:240]
        plans: dict[str, PacketPlan] = {}
        gammas: dict[str, dict[str, Any]] = {}
        # A step the requester refuses to send (a search step with no safe
        # public query) fails honestly on its own; it does not abort the plan.
        pre_failed: dict[str, TaskFailed] = {}
        evidence_blocks, evidence_report = self._evidence(plan, path, lang, lane, cfg)
        for task in plan.tasks:
            level_no, index = positions[task.task_id]
            role = str((task_roles or {}).get(task.task_id)
                       or getattr(task, "role", "") or "")
            instruction = localise_instruction(
                _with_block(task.instruction, evidence_blocks.get(task.task_id, "")),
                lang, path)
            if role == "search":
                # WP4b, D-018: a search task carries ONLY a public query: no
                # Γ, no predecessors, no conversation. If the guard cannot
                # produce a query without the requester's private terms,
                # nothing is sent and this step fails honestly.
                instruction = self._public_query_for(task.instruction, project_id)
                if not instruction:
                    pre_failed[task.task_id] = TaskFailed(
                        f"{task.task_id}: role 'search' has no public query "
                        "without private terms; nothing was sent",
                        code="E_PUBLIC_QUERY", reason="policy_refusal")
                    continue
            plans[task.task_id] = PacketPlan(
                task_id=task.task_id, wire_task_id="", level=level_no, index=index,
                instruction=instruction,
                consumes=bool(consumed[task.task_id]),
                depends_on=tuple(task.depends_on), lane=lane,
                role=role)
            gammas[task.task_id] = gamma_for(contract, objective, task.instruction,
                                             self._clamp(budgets[task.task_id], workers),
                                             lang)
        timeout_s = float(swarm_cfg.get("timeout_ms", 60000)) / 1000.0
        temperature = float(cfg["model"].get("temperature", 0.2))

        def make_builder(task_id: str, carries: dict[str, str]):
            def build(attempt: int, family: str | None,
                      model: str | None = None) -> dict[str, Any]:
                if plans[task_id].role == "search":
                    # Only the public query; the scheduler injects the role.
                    return build_search_message(
                        plans[task_id], session_id, attempt,
                        deadline_ms=int(timeout_s * 1000), tier=decision["tier"])
                return build_message(
                    plans[task_id], gammas[task_id], session_id, attempt, carries,
                    positions, max_tokens=self._clamp(budgets[task_id], workers),
                    deadline_ms=int(timeout_s * 1000), tier=decision["tier"],
                    temperature=temperature, model_family=family, model=model)
            return build

        preview = [make_builder(t.task_id, {})(0, None) for t in plan.tasks
                   if t.task_id not in pre_failed]
        rho = measure_rho(preview, text)
        session_hex = contract.session_id
        for message in preview:
            leaks = contains_identifier(message, session_hex,
                                        text if directory.remote_allowed else "")
            if leaks:  # a refusal, not a warning
                raise RuntimeError("privacy self-check blocked dispatch: packet "
                                   f"would carry {', '.join(leaks)}")
        tracker.complete("PACKET GENERATION", n_packets=len(preview),
                         rho_achieved=rho["rho_achieved"], rho_floor=rho["rho_floor"],
                         gamma_chars_max=rho["gamma_chars_max"],
                         max_packet_prompt_fraction=rho["max_packet_prompt_fraction"],
                         max_tokens_per_task=self._clamp(max_tokens, workers),
                         privacy_check=("passed: no session id, no complete request"
                                        if directory.remote_allowed else
                                        "local pool only: nothing leaves the device"))

        tracker.start("NODE SELECTION")
        k_min = max(1, int(swarm_cfg.get("k_min", 1)))
        k_max = max(k_min, int(swarm_cfg.get("k_max", k_min + 1)))
        families = sorted({str(m.get("family") or "unknown") for w in workers
                           for m in (w.advertisement.get("models") or [])})
        tracker.complete("NODE SELECTION", workers=len(workers), families=families,
                         local_pool=any(getattr(w, "source", "") == "local" for w in workers),
                         k_min=k_min, k_max=k_max,
                         roles_requested=sorted({p.role for p in plans.values() if p.role}),
                         policy="maximise model-family diversity per task, "
                                "then distinct machines, then lowest load; "
                                "a role task only on a worker advertising it")

        scheduler = Scheduler(
            directory, self.bus, request_id, k_min=k_min, k_max=k_max,
            max_concurrency=int(swarm_cfg.get("max_concurrency", 4)),
            timeout_s=timeout_s,
            hedge_fallback_s=float(swarm_cfg.get("hedge_fallback_ms",
                                                 int(timeout_s * 500))) / 1000.0,
            latency=self.latency,
            min_params_b=float(swarm_cfg.get("min_model_params_b", 1.5)),
            queue_retries=not (self.local_stream is not None and self.local_model),
            speed=self.speed, passage_texts=passage_texts,
            role_stats=self.role_stats, credits=self.credits)
        carries: dict[str, str] = {}
        resolved: dict[str, dict[str, Any]] = {}
        local_fallbacks: list[str] = []
        local_role_fallbacks: list[dict[str, Any]] = []
        local_rejected: list[str] = []
        tie_breaks: list[dict[str, Any]] = []
        # Tasks whose result is corpus material: their text may only be
        # forwarded to a destination allowed to receive passages (WP4b).
        sensitive_tasks: set[str] = set()
        tie_break = bool(swarm_cfg.get("tie_break", True))
        embedder, embedder_name = self._embedder()

        async def local_rescue(task_id: str, build, check, reason: str,
                               passages: bool = False):
            """This device's model on the packet, then on the bare task.

            The bare task drops the contract header: on 22 Oct 2026 (P3d.1)
            the same 3B model that translated the whole list correctly echoed
            the Spanish words when the fragment came wrapped in the contract.
            Returns ``(replica, passed_check)``; ``(None, False)`` when there
            is no local model.
            """
            loop = asyncio.get_running_loop()
            message = build(0, None)
            last = None
            for variant in (message, {"task": message.get("task") or {}}):
                replica = await loop.run_in_executor(
                    None, egress.carry(functools.partial(
                        self._local_fallback, task_id, variant,
                        self._clamp(budgets[task_id], []), reason,
                        passages=passages)))
                if replica is None:
                    break
                last = replica
                if check is None or check(replica.text):
                    return replica, True
            if last is not None:
                local_rejected.append(task_id)
            return last, False

        async def run_one(task_id: str):
            if task_id in pre_failed:
                raise pre_failed[task_id]
            build = make_builder(task_id, carries)
            loop = asyncio.get_running_loop()
            check = validators.get(task_id)
            requested_role = plans[task_id].role
            # A search task carries only its public query (no predecessors),
            # so a corpus predecessor is not forwarded by it.
            requires_passages = (requested_role != "search"
                                 and bool(set(consumed[task_id]) & sensitive_tasks))
            try:
                replicas = await scheduler.run_task(task_id, build, budgets[task_id],
                                                    validate=check,
                                                    role=requested_role,
                                                    require_passages=requires_passages)
            except TaskFailed as exc:
                # A search or corpus task has no truthful generic substitute:
                # without its executor the right answer is an honest failure.
                if requested_role and requested_role not in ("large_model", "reasoner"):
                    raise
                # Every remote attempt failed (node gone, deadline, policy).
                # The task is run on this device's model rather than failing
                # the whole answer (P3b.3, 22 Oct 2026: losing the largest
                # node made one section fail and the request with it).
                fallback, ok = await local_rescue(task_id, build, check, str(exc),
                                                  passages=requires_passages)
                if fallback is not None and requested_role:
                    local_role_fallbacks.append(
                        {"task": task_id, "role": requested_role,
                         "node": self.local_model or "local model",
                         "reason": "no role worker answered"})
                if fallback is None:
                    raise
                if not ok:
                    fallback.telemetry = dict(fallback.telemetry or {}, degraded=True)
                replicas = [fallback]
                local_fallbacks.append(task_id)
            if check is not None and replicas and all(
                    (r.telemetry or {}).get("degraded") for r in replicas) and not (
                    task_id in local_fallbacks):
                # Every remote replica failed the quality check (e.g. all of
                # them echoed the Spanish words, P3c.1): try this device's
                # model before accepting a degraded answer.
                fallback, ok = await local_rescue(task_id, build, check,
                                                  "all replicas rejected",
                                                  passages=requires_passages)
                if fallback is not None and ok:
                    replicas = [fallback]
                    local_fallbacks.append(task_id)
            if path == "enumerated" and tie_break and len(replicas) == 2 and not any(
                    (r.telemetry or {}).get("degraded") for r in replicas):
                items = _item_texts(plan_by_id[task_id].instruction)
                split = _split_items(replicas, items)
                if split:
                    # Two replicas that disagree cannot be decided by a vote;
                    # one more replica on another family breaks the tie, only
                    # on a worker that is free now (P3k.1: a tie-break queued
                    # behind a cold model load added 60 s and then failed)
                    # (P3g.1, 23 Oct 2026: "carro / leite / vermelho" won
                    # over "car / milk / red" as the better-ranked replica).
                    try:
                        extra = await scheduler.run_task(
                            task_id, build, budgets[task_id], validate=check,
                            k_min=1, k_max=1, start_number=len(scheduler.attempts),
                            reason="tie_break", free_only=True,
                            exclude={(r.node_id, r.family) for r in replicas},
                            role=plans[task_id].role,
                            require_passages=requires_passages)
                    except TaskFailed:
                        extra = []
                    extra = [r for r in extra if not (r.telemetry or {}).get("degraded")]
                    if extra:
                        replicas = replicas + extra[:1]
                        tie_breaks.append({"task": task_id, "items": split})
            outcome = await loop.run_in_executor(
                None, egress.carry(functools.partial(
                    self._resolve, task_id, replicas, contract, embedder,
                    policy="items" if path == "enumerated" else "whole",
                    lang=lang, budget=self._clamp(budgets[task_id], workers),
                    items=(_item_texts(plan_by_id[task_id].instruction)
                           if path == "enumerated" else None),
                    required=required_by_task.get(task_id),
                    critical=critical_by_task.get(task_id),
                    target_words=(outline.sections[_order(task_id)].words
                                  if outline is not None
                                  and outline.sections[_order(task_id)].kind != "table"
                                  else None))))
            resolved[task_id] = outcome
            if any(rep.executor == "corpus" for rep in replicas):
                sensitive_tasks.add(task_id)
            carries[task_id] = planner.summarize_fragment(outcome["text"], typed=True)
            return outcome

        plan_by_id = {t.task_id: t for t in plan.tasks}
        validators = self._validators(plan, path, outline)
        required_by_task = ({f"t{i}": [k for req in sec.must_include
                                       for k in composer.requirement_keys(req)]
                             for i, sec in enumerate(outline.sections) if sec.kind != "table"}
                            if outline is not None else {})
        critical_by_task = ({f"t{i}": [k for req in sec.must_include
                                       for k in composer.proper_keys(req)]
                             for i, sec in enumerate(outline.sections) if sec.kind != "table"}
                            if outline is not None else {})
        order = [t.task_id for t in sorted(plan.tasks, key=lambda t: positions[t.task_id])]
        for name in ("DISPATCHING", "MODEL EXECUTION", "RESULT RECEPTION"):
            tracker.start(name)
        outcome = LevelsOutcome()
        deadline = time.monotonic() + timeout_s * max(2, k_max) * len(levels) + 30
        future = asyncio.run_coroutine_threadsafe(
            run_levels(scheduler, order, consumed, run_one, outcome=outcome,
                       deadline=deadline, cancel=cancel), self._loop())
        while True:
            try:
                future.result(timeout=0.2)
                break
            except RunCancelled:
                raise Cancelled()
            except concurrent.futures.TimeoutError:
                pass
            if cancel is not None and cancel.is_set():
                future.cancel()
                raise Cancelled()
            if time.monotonic() > deadline + 5:
                future.cancel()
                raise RuntimeError("distributed execution exceeded its global deadline")

        # Only a step whose state says completed may enter assembly. This
        # also covers a global deadline that cancelled a task after it had
        # already written its side-effect result.
        resolved = {task_id: value for task_id, value in resolved.items()
                    if outcome.state(task_id).status == "completed"}
        # D-019: what completed, what did not and why. A step that was never
        # run because a predecessor failed says which step blocked it.
        steps_meta: list[dict[str, Any]] = []
        for task_id in order:
            state = outcome.state(task_id)
            task = plan_by_id[task_id]
            steps_meta.append({
                "step": task_id,
                "name": team_labels.get(task_id) or _task_label(task),
                "role": str((task_roles or {}).get(task_id)
                            or getattr(task, "role", "") or ""),
                **state.to_dict()})
        completed_steps = [s for s in steps_meta if s["status"] == "completed"]
        missing_steps = [s for s in steps_meta if s["status"] != "completed"]
        if not completed_steps:
            answer_status = "failed"
        elif missing_steps:
            answer_status = "partial"
        else:
            answer_status = "complete"

        attempts = [a.to_dict() for a in scheduler.attempts]
        accepted = [a for a in scheduler.attempts if a.status in ("accepted", "degraded")]
        failed = [a for a in scheduler.attempts if a.status == "failed"]
        role_fallbacks = [
            {"task": a["task"], "role": a["role"], "node": a["node"]}
            for a in attempts if a.get("role_fallback")] + local_role_fallbacks
        role_failed = [
            {"task": a.task_id, "role": a.role, "node": a.node_id[:12],
             "code": a.code}
            for a in failed if a.role]
        if role_fallbacks:
            routing_meta["role_unavailable"] = role_fallbacks
        tracker.complete("DISPATCHING", attempts=len(attempts), hedges=scheduler.hedges,
                         retries=scheduler.retries, rejected_quality=scheduler.rejected,
                         role_fallbacks=role_fallbacks, role_failed=role_failed,
                         missing_steps=[{"step": s["step"], "reason": s.get("reason", "")}
                                        for s in missing_steps],
                         hedge_timer=",".join(sorted(scheduler.hedge_timer_source)))
        tracker.complete("MODEL EXECUTION",
                         gen_ms_total=sum(int((a.get("telemetry") or {}).get("gen_ms") or 0)
                                          for r in resolved.values()
                                          for a in r["replica_meta"]),
                         tokens_out=sum(int(a.tokens_out or 0) for a in accepted))
        tracker.complete("RESULT RECEPTION", accepted=len(accepted), failed=len(failed),
                         timeouts=scheduler.timeouts)

        signature_failures = sum(1 for a in scheduler.attempts if a.code == "E_VERIFY_FAILED")
        schema_failures = sum(1 for a in scheduler.attempts if a.code == "E_SCHEMA")
        tracker.start("VERIFICATION")
        tracker.partial("VERIFICATION", signatures_checked=len(accepted) + signature_failures,
                        signature_failures=signature_failures,
                        schema_failures=schema_failures,
                        layer1_commitment="not available (SPEC §21.1: no normative "
                                          "construction) — not simulated",
                        sampled_audit="not available")

        multi = {tid: r for tid, r in resolved.items() if r["consensus"] is not None}
        if multi:
            tracker.start("CONSENSUS / ALIGNMENT")
            tracker.complete("CONSENSUS / ALIGNMENT", tasks=len(multi),
                             policy=("item vote (majority per numbered item); "
                                     "per-unit alignment reported as divergence"
                                     if path == "enumerated" else
                                     "whole-replica selection; per-unit alignment "
                                     "reported as divergence only"),
                             mean_agreement=round(sum(r["consensus"]["mean_agreement"]
                                                      for r in multi.values()) / len(multi), 4),
                             thresholds="placeholder α (uncalibrated)",
                             caveat="agreement is convergence, not correctness; "
                                    "cross-family errors are correlated (L23)")
            waived = None
        else:
            waived = ("k_min=1_requested" if k_min == 1
                      else "insufficient_distinct_node_family_pairs")
            tracker.skip("CONSENSUS / ALIGNMENT", waived)

        tracker.start("ASSEMBLY")
        role_sources = self._role_sources(resolved)
        bridge_backend = LocalPromptBackend(self.local_stream, self.local_model)
        if any(source.get("kind") == "corpus" for source in role_sources) \
                and not self._local_model_passages_allowed():
            # Corpus material is the requester's passage material. If this
            # device's model is a third-party service without
            # privacy.third_party_passages, no bridge text may be generated
            # from it; the fragments are spliced without a bridge.
            bridge_backend = LocalPromptBackend(None, "")
        if outline is not None:
            texts, seams, seam_policy = self._assemble_composition(
                plan, outline, resolved, embedder)
        else:
            texts, seams, seam_policy = self._assemble(plan, contract, resolved,
                                                       bridge_backend, embedder, adm.path)
        tracker.complete("ASSEMBLY", n_seams=len(seams), seam_policy=seam_policy,
                         bridges=sum(1 for s in seams if s["path"] == "bridge"),
                         bridge_failures=bridge_backend.failures,
                         embedder=embedder_name)

        truncated = sorted(tid for tid, r in resolved.items() if r.get("truncated"))

        tracker.start("COHERENCE REPORT")
        coherence = self._coherence(texts, seams, embedder_name)
        tracker.complete("COHERENCE REPORT", **{k: v for k, v in coherence.items()
                                                if k != "errors"})
        # D-019: a partial answer names every step that could not be completed
        # and why. A list keeps its per-item statuses and is rebuilt by the
        # recipe; adding prose there would corrupt the table.
        partial_note = ""
        if missing_steps:
            partial_note = _missing_note(lang, missing_steps)
            if answer_status == "partial" and path != "enumerated" and texts:
                texts = texts.rstrip() + "\n\n" + partial_note

        participants = {}
        for a in accepted:
            is_local = getattr(directory.peers.get(a.node_id), "source", "") == "local"
            participants.setdefault((a.node_id, a.model), {
                "node": a.node_id[:12], "family": a.family, "version": a.model,
                "role": "local model" if is_local else "worker", "tasks": 0})
            participants[(a.node_id, a.model)]["tasks"] += 1
        p_observed = (len(failed) / len(attempts)) if attempts else 0.0
        c = (len(attempts) / len(plan.tasks)) if plan.tasks else 0.0
        total_ms = int((time.time() - started) * 1000)
        consensus_meta = None
        if multi:
            consensus_meta = {
                "k_min": k_min, "k_max": k_max,
                "families": sorted({f for r in multi.values()
                                    for f in r["consensus"]["families"]}),
                "mean_agreement": round(sum(r["consensus"]["mean_agreement"]
                                            for r in multi.values()) / len(multi), 4),
                "per_task": {tid: r["consensus"] for tid, r in multi.items()},
                "policy": ("item_vote" if path == "enumerated" else "whole_replica"),
                "alpha_high": multi[next(iter(multi))]["consensus"]["alpha_high"],
                "alpha_low": multi[next(iter(multi))]["consensus"]["alpha_low"],
                "thresholds_source": "swarmbly_v0 provisional defaults (uncalibrated)",
                "interpretation": "agreement, not accuracy (SPEC §14b.6, L13, L23)",
            }
        metadata = {
            **{k: rho[k] for k in ("rho_achieved", "rho_target", "rho_floor",
                                   "rho_reachable", "rho_policy")},
            # 3.5, D-019: complete | partial | failed, and the state of every
            # step (completed, failed with a reason, or blocked by a step).
            "status": answer_status,
            "steps": steps_meta,
            "missing_steps": missing_steps,
            "partial_note": partial_note,
            "team": team_meta,
            "n_tasks": len(plan.tasks), "n_levels": len(levels),
            "language": lang,
            "length": {"target_words": request.target_words,
                       "explicit": request.length_explicit,
                       "max_tokens_per_task": self._clamp(max_tokens, workers)},
            "truncated_tasks": truncated,
            "composition": ({"outline": outline.to_dict(),
                             "requirements": composer.requirement_report(outline, texts),
                             "target_words": request.target_words}
                            if outline is not None else None),
            "max_packet_prompt_fraction": rho["max_packet_prompt_fraction"],
            "tau_sem": self._tau_sem(), "tau_source": self._tau_source(embedder_name),
            "seams": seams,
            "coherence": coherence,
            "verification": {"commitments_checked": 0, "failures": signature_failures,
                             "audited": 0, "signatures_checked":
                             len(accepted) + signature_failures,
                             "commitment": "not_available"},
            "consensus": consensus_meta,
            "consensus_waived_reason": waived,
            "coverage": {"c": round(c, 3), "p_observed": round(p_observed, 3),
                         "c_eff": round(c * (1 - p_observed), 3),
                         "expected_uncovered_fraction": round(p_observed ** max(c, 1), 4),
                         "source": "measured attempts of this request (estimate)"},
            "routing": routing_meta,
            "nodes": list(participants.values()),
            "router": router_meta,
            "attempts": attempts,
            "hedges": scheduler.hedges, "retries": scheduler.retries,
            "rejected_quality": scheduler.rejected,
            "local_fallback_tasks": sorted(local_fallbacks),
            "local_fallback_rejected": sorted(set(local_rejected)),
            # 3.5, D-018: requested roles, honest substitutions and what this
            # requester observed per (node, role). Never the peer's own claim.
            "role_fallbacks": role_fallbacks,
            "role_failed": role_failed,
            "role_outcomes": (scheduler.role_stats.snapshot()
                              if any(a.get("role") for a in attempts) else []),
            # WP4b: material returned by the search/corpus executors, with the
            # circle and member the requester sent to. Corpus entries are
            # third-party passages, never the requester's own sources.
            "role_sources": role_sources,
            "evidence": evidence_report,
            "tie_breaks": tie_breaks,
            "timeouts": scheduler.timeouts,
            "bytes": {"out": sum(a["bytes_out"] for a in attempts),
                      "in": sum(a["bytes_in"] for a in attempts)},
            "stage_ms": tracker.timings(),
            "total_ms": total_ms,
            "embedder": embedder_name,
            "seam_policy": seam_policy,
            "mode": mode,
            "spec": "SwarmblyAI SPEC v0.2 (rev. 2); app extensions documented",
        }
        if self.stats_sink is not None:
            try:
                self.stats_sink(dispatched=len(attempts), dispatch_failed=len(failed),
                                distributed_requests=1)
            except Exception:
                pass
        tracker.start("FINAL RESPONSE")
        tracker.complete("FINAL RESPONSE", total_ms=total_ms)
        return {"routed": "distributed", "text": texts, "metadata": metadata,
                "status": answer_status, "stages": tracker.list()}

    # -- pieces ---------------------------------------------------------------------
    @staticmethod
    def _team_plan(team: Any, text: str):
        """A stored team as an ordinary plan: substitution, deps and roles.

        Dependencies are data edges here (not guessed from the instruction):
        a team says which earlier step it consumes, so the same template is
        dispatched the same way on one node or several. ``{request}`` is the
        user's request, substituted into the step templates.
        """
        from swarmbly_v0.schema import Plan, Task
        steps = list((team or {}).get("steps") or [])
        index: dict[str, int] = {}
        tasks: list[Task] = []
        roles: dict[str, str] = {}
        labels: dict[str, str] = {}
        for number, step in enumerate(steps):
            step_id = str(step.get("id") or f"s{number + 1}")
            depends = []
            for dep in step.get("depends_on") or []:
                dep = str(dep)
                if dep not in index:
                    raise ValueError(
                        f"team step {step_id!r} depends on {dep!r}, which is "
                        "not an earlier step")
                depends.append(f"t{index[dep]}")
            task_id = f"t{number}"
            instruction = str(step.get("instruction") or "").replace(
                "{request}", text)
            tasks.append(Task(task_id=task_id, instruction=instruction,
                              depends_on=tuple(depends)))
            roles[task_id] = str(step.get("role") or "")
            labels[task_id] = str(step.get("name") or task_id)
            index[step_id] = number
        if not tasks:
            raise ValueError("a team needs at least one step")
        return Plan(prompt=text, tasks=tasks), roles, labels

    def _resolve(self, task_id, replicas, contract, embedder, *, policy: str = "units",
                 lang: str | None = None, budget: int | None = None,
                 items: dict[int, str] | None = None,
                 required: list[str] | None = None,
                 target_words: int | None = None,
                 critical: list[str] | None = None) -> dict[str, Any]:
        """One text per task: the only replica, or a consensus over replicas (§14b).

        ``policy="units"`` (independent items of a batch) returns upstream's
        per-unit consensus text. ``policy="whole"`` (a composition, a whole
        request) selects ONE complete replica: upstream per-unit consensus
        picks a medoid per unit, which on two different essays produced a
        patchwork of both, in two languages (diagnosis 2026-10-15, finding 5).
        The per-unit alignment is still computed and reported as divergence.

        ``policy="items"`` (an enumerated batch) votes per numbered item: each
        replica's answer to item *n* is parsed, the majority value wins, ties
        go to the best-ranked replica (as in ``"whole"``). Per-unit alignment
        on short answer sheets appended a second replica's re-listed items to
        the first (live smoke test 2026-10-16). When fewer than half the items
        can be parsed, the policy falls back to ``"whole"``.
        """
        meta = [{"node": r.node_id[:12], "family": r.family, "model": r.model,
                 "elapsed_ms": r.elapsed_ms, "telemetry": r.telemetry,
                 "truncated": _is_truncated(r, budget),
                 "sources": r.sources, "executor": r.executor,
                 "circle_id": r.circle_id, "circle_name": r.circle_name,
                 "member_name": r.member_name}
                for r in replicas]
        if len(replicas) < 2:
            text = replicas[0].text
            if policy == "items" and items:
                text = _normalise_items(text, items, lang,
                                        bool((replicas[0].telemetry or {}).get("degraded")))
            return {"text": text, "consensus": None, "replica_meta": meta,
                    "truncated": meta[0]["truncated"]}
        from swarmbly_v0.consensus import Replica as UpReplica, consensus
        result = consensus([UpReplica(replica_id=f"r{i}", text=r.text, family=r.family,
                                      model=r.model) for i, r in enumerate(replicas)],
                           contract, embedder)
        block = {
            "k": result.k, "families": list(result.families),
            "mean_agreement": round(float(result.mean_agreement), 4),
            "units": [{"label": u.label, "agreement": round(float(u.agreement), 4),
                       "text": u.text[:160]} for u in result.units],
            "low_confidence_regions": [
                {"start": r.start, "end": r.end,
                 "mean_agreement": round(float(r.mean_agreement), 4),
                 "text": r.text[:200]} for r in result.low_confidence_regions],
            "alpha_high": result.alpha_high, "alpha_low": result.alpha_low,
        }
        if policy == "units":
            return {"text": result.text or replicas[0].text, "consensus": block,
                    "replica_meta": meta,
                    "truncated": all(m["truncated"] for m in meta)}
        chosen, selection = _select_whole(replicas, meta, embedder, lang, required,
                                          target_words, critical)
        if policy == "items" and items:
            vote = _vote_items(replicas, items, selection["ranking"], lang)
            if vote is not None:
                text, report = vote
                block["selection"] = report
                return {"text": text, "consensus": block, "replica_meta": meta,
                        "truncated": False}
        block["selection"] = selection
        text = replicas[chosen].text
        if policy == "items" and items:
            text = _normalise_items(text, items, lang, bool(
                (replicas[chosen].telemetry or {}).get("degraded")))
        return {"text": text, "consensus": block, "replica_meta": meta,
                "truncated": meta[chosen]["truncated"]}

    def _assemble(self, plan, contract, resolved, bridge_backend, embedder, path):
        """Select-then-splice (SPEC §14). For an enumerated batch the items
        are independent by construction: junctions are spliced, never bridged
        (a transition sentence between list items only adds noise); seam
        similarities are still measured and reported."""
        from swarmbly_v0.assembler import fragments_from_mapping, select_then_splice
        mapping = {t.task_id: [resolved[t.task_id]["text"]] for t in plan.tasks
                   if t.task_id in resolved}
        fragments = fragments_from_mapping(mapping, plan=plan)
        if path == "enumerated":
            tau, join, policy = -2.0, True, "list: independent items, spliced (no bridges)"
        else:
            tau, join, policy = self._tau_sem(), False, "τ_sem: bridge below threshold"
        assembly = select_then_splice(fragments, contract, bridge_backend, tau,
                                      plan=plan, embedder=embedder,
                                      paragraph_join=join)
        seams = [{"left": s.left_task, "right": s.right_task,
                  "similarity": round(float(s.similarity), 4),
                  "path": "bridge" if s.bridged else "splice"}
                 for s in assembly.seams]
        if path == "enumerated":
            # One answer per line, in item order. The upstream splice adds a
            # period at each fragment's end ("4. Reptil."), which changes the
            # answer itself; the seams above are still its measurement.
            ordered = sorted((t for t in plan.tasks if t.task_id in resolved),
                             key=lambda t: _order(t.task_id))
            text = "\n".join(resolved[t.task_id]["text"].strip() for t in ordered)
            return text, seams, policy
        return assembly.text, seams, policy

    @staticmethod
    def _evidence(plan, path: str, lang: str, lane: str, cfg: dict[str, Any]):
        """Public evidence per fragment (P2 prototype, ``evidence.enabled``).

        Only for enumerated batches of a PUBLIC request; only item texts are
        sent to the provider. Returns ``({task_id: block}, report)``.
        """
        ev_cfg = cfg.get("evidence") or {}
        if not ev_cfg.get("enabled"):
            return {}, None
        if path != "enumerated":
            return {}, {"skipped": "not an enumerated batch"}
        if lane != "PUBLIC":
            return {}, {"skipped": f"lane {lane}: nothing leaves for a public lookup"}
        from . import evidence as ev
        lang_ = lang if lang in ev.SUPPORTED_LANGS else "en"
        provider = ev.batch_provider(lang_, ev_cfg)
        items_by_task = {t.task_id: _item_texts(t.instruction) for t in plan.tasks}
        all_items = {n: text for items in items_by_task.values() for n, text in items.items()}
        started = time.monotonic()
        profile = None
        if ev_cfg.get("operation_aware", True) and plan.tasks:
            first = plan.tasks[0].instruction or ""
            preamble = re.split(r"^\s*[\[(]?\d{1,3}[\]).:]\s", first, maxsplit=1,
                                flags=re.M)[0]
            profile = ev.operation_profile(preamble)
        found, report = ev.gather(all_items, provider, int(ev_cfg.get("max_items", 24)),
                                  profile)
        report["ms"] = int((time.monotonic() - started) * 1000)
        blocks = {}
        for task_id, items in items_by_task.items():
            block = ev.render({n: found[n] for n in items if n in found}, lang_)
            if block:
                blocks[task_id] = block
        return blocks, report

