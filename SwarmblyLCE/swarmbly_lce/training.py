@dataclass
class AdapterManager:
    wiki: Wiki
    base_model: str
    trainer: Trainer
    evaluator: Evaluator
    params: Params = DEFAULT
    registry: TestSetRegistry = field(default_factory=TestSetRegistry)
    current: Adapter | None = None
    history: list[dict] = field(default_factory=list)
    generation: int = 0
    affected_since: int | None = None

    def run_generation(self, new: Sequence[Example], replay: Sequence[Example], general: Sequence[Example],
                       recipes: Sequence[Recipe], social: Sequence[Example] = ()) -> Adapter | None:
        if not 1 <= len(recipes) <= max(1, self.params.n_candidates * 4):
            raise ValueError("number of candidate recipes out of range")
        self.generation += 1
        composer = BatchComposer(self.params)
        candidates: list[Adapter] = []
        used_examples: set[str] = set()
        for r in recipes:
            batch = composer.compose(new, replay, general, social, r, self.wiki)
            a = self.trainer.train(self.base_model, batch, self.generation)
            if a.init_from != self.base_model:
                raise InvariantViolation("I6", "candidate not initialised from the base model")
            candidates.append(a)
            used_examples |= {cid for e in batch.examples for cid in e.claim_ids}
        test = self.registry.fresh(self.wiki, self.generation, used_examples, seed=self.generation)
        scored = [(a, self.evaluator.evaluate(a, test, self.current)) for a in candidates]
        winner = Gate(self.params).choose(scored)
        self.history.append({
            "generation": self.generation,
            "test_id": test.test_id,
            "candidates": [{"adapter": a.adapter_id, "recipe": a.recipe.recipe_id, "gain": s.wiki_gain,
                            "loss": s.general_loss, "abstain": s.abstain_rate, "passes": s.passes(self.params)} for a, s in scored],
            "winner": winner.adapter_id if winner else None,
        })
        if winner is not None:
            self._register(winner, new)
            self.current = winner
            self.affected_since = None
        return winner

    def _register(self, adapter: Adapter, new: Sequence[Example]) -> None:
        g = self.wiki.graph
        anode = f"adapter:{adapter.adapter_id}"
        g.add_node(anode, "adapter")
        for e in new:
            enode = f"example:{e.example_id}"
            if e.example_id not in adapter.example_ids:
                continue
            g.add_node(enode, "example")
            for cid in e.claim_ids:
                cnode = f"claim:{cid}"
                if cnode in g.kinds and enode not in g.children.get(cnode, set()):
                    g.add_edge(cnode, enode)
            if anode not in g.children.get(enode, set()):
                g.add_edge(enode, anode)

    def current_affected(self) -> bool:
        return self.current is not None and f"adapter:{self.current.adapter_id}" in self.wiki.graph.affected_adapters()

    def enforce_forgetting(self) -> bool:
        """Retire the current adapter if affected for more than FORGET_MAX_CYCLES (SPEC 7.8.2)."""
        if not self.current_affected():
            self.affected_since = None
            return False
        if self.affected_since is None:
            self.affected_since = self.wiki.cycle
        if self.wiki.cycle - self.affected_since >= self.params.forget_max_cycles - 1:
            self.wiki.graph.remove(f"adapter:{self.current.adapter_id}")
            self.current = None
            return True
        return False


@dataclass
class MLXLoRATrainer:
    """EXPERIMENTAL: train a LoRA with ``mlx_lm`` on Apple Silicon.

    Not exercised in CI. Writes the batch as JSONL chat data and calls
    ``python -m mlx_lm.lora``. Requires ``pip install mlx-lm``.
    """

    workdir: str
    iters: int = 200
    batch_size: int = 4

    @staticmethod
    def available() -> bool:
        try:
            import mlx_lm  # type: ignore  # noqa: F401
            return True
        except Exception:
            return False

    def export(self, batch: Batch, path: Path) -> None:
        path.mkdir(parents=True, exist_ok=True)
        rows = [{"messages": [{"role": "user", "content": e.prompt}, {"role": "assistant", "content": e.response}]}
                for e in batch.examples if e.kind != "preference_pair"]
        n_valid = max(1, len(rows) // 10)
        (path / "train.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows[n_valid:]) + "\n", encoding="utf-8")
        (path / "valid.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows[:n_valid]) + "\n", encoding="utf-8")

    def train(self, base_model: str, batch: Batch, generation: int) -> Adapter:
        if not self.available():
            raise RuntimeError("mlx_lm is not installed; use MockTrainer or install mlx-lm on Apple Silicon")
        r = batch.recipe
        out = Path(self.workdir) / f"gen{generation}_{r.recipe_id}"
        data = out / "data"
        self.export(batch, data)
        cmd = [sys.executable, "-m", "mlx_lm.lora", "--model", base_model, "--train", "--data", str(data),
               "--adapter-path", str(out / "adapter"), "--iters", str(self.iters), "--batch-size", str(self.batch_size),
               "--learning-rate", str(r.lr), "--seed", str(r.seed)]
        subprocess.run(cmd, check=True)
        aid = digest16({"b": base_model, "r": r.recipe_id, "g": generation})
        return Adapter(aid, base_model, r, tuple(sorted({e.example_id for e in batch.examples})), init_from=base_model,
                       generation=generation, path=str(out / "adapter"))
