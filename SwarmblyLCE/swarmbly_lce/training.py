# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Example:
    kind: str  # "style" | "qa" | "preference_pair" | "replay" | "general"
    prompt: str
    response: str
    rejected: str = ""
    claim_ids: tuple[str, ...] = ()
    origin: str = "self"  # "self" | "social"
    epistemic_distance: int = 0
    human_source: str = "self"
    generator: str = "base"  # "base" | "adapter:<id>" — text generated by an adapter is forbidden

    @property
    def example_id(self) -> str:
        return digest16({"k": self.kind, "p": self.prompt, "r": self.response, "x": self.rejected})


@dataclass(frozen=True)
class Recipe:
    rank: int = 8
    alpha: int = 16
    lr: float = 1e-4
    epochs: int = 2
    replay_fraction: float = DEFAULT.replay_fraction
    general_fraction: float = DEFAULT.general_fraction
    social_fraction: float = 0.0
    seed: int = 0

    @property
    def recipe_id(self) -> str:
        return digest16(asdict(self))


@dataclass
class Batch:
    examples: list[Example]
    recipe: Recipe

    @property
    def social_share(self) -> float:
        return sum(e.origin == "social" for e in self.examples) / max(1, len(self.examples))

    @property
    def replay_share(self) -> float:
        return sum(e.kind == "replay" for e in self.examples) / max(1, len(self.examples))


@dataclass
class Adapter:
    adapter_id: str
    base_model: str
    recipe: Recipe
    example_ids: tuple[str, ...]
    init_from: str  # always the base model (I6)
    generation: int
    path: str = ""
    true_quality: float | None = None  # simulation only
    contains_facts: bool = False


@dataclass
class GateScores:
    wiki_gain: float  # points over the current adapter / base on memory questions
    general_loss: float  # points lost on the general benchmark
    abstain_rate: float  # fraction of out-of-memory questions where it abstains

    def passes(self, params: Params = DEFAULT) -> bool:
        return (self.wiki_gain >= params.gate_min_gain and self.general_loss <= params.gate_max_loss
                and self.abstain_rate >= params.gate_min_abstain)


@dataclass(frozen=True)
class TestSet:
    __test__ = False  # not a pytest class
    test_id: str
    generation: int
    questions: tuple[tuple[str, str], ...]  # (question, reference answer)
    out_of_memory: tuple[str, ...] = ()


# ---------------------------------------------------------------------------
# Eligibility and example building
# ---------------------------------------------------------------------------

def eligible(example: Example, wiki: Wiki, params: Params = DEFAULT) -> bool:
    """SPEC 7.1 plus I1/I3. Returns False rather than raising: callers filter."""
    if example.generator != "base":
        return False
    if example.epistemic_distance > params.epistemic_max_share_train:
        return False
    if example.kind in {"replay", "general"}:
        return True
    if example.kind == "preference_pair":
        return bool(example.rejected)
    if not example.claim_ids:
        return False
    for cid in example.claim_ids:
        c = wiki.claims.get(cid)
        if c is None or c.maturity != Maturity.TRAINABLE or wiki.graph.is_stale(f"claim:{cid}"):
            return False
        if not c.behavioural:
            return False
        if any(wiki.policy.rule_for(a.source).reference_only for a in c.anchors):
            return False
        if example.kind == "style" and not all(wiki.policy.rule_for(a.source).authored_by_user for a in c.anchors):
            return False
    return True


@dataclass
class ExampleBuilder:
    wiki: Wiki

    def from_claims(self) -> list[Example]:
        out: list[Example] = []
        for c in sorted(self.wiki.trainable(), key=lambda x: x.claim_id):
            if c.type == ClaimType.STYLE:
                out.append(Example("style", "Write in my usual voice.", c.text, claim_ids=(c.claim_id,),
                                   epistemic_distance=c.provenance.epistemic_distance))
            else:
                q = ("How do you usually do this?" if c.type == ClaimType.PROCEDURE else "What do you prefer here?")
                # The reference answer IS the anchored claim, whose span was verified
                # when the claim reached ANCHORED (SPEC 7.2.2).
                out.append(Example("qa", q, c.text, claim_ids=(c.claim_id,),
                                   epistemic_distance=c.provenance.epistemic_distance))
        return out

    @staticmethod
    def correction(before: str, after: str, prompt: str = "Rewrite as I would.") -> Example:
        return Example("preference_pair", prompt, after, rejected=before, epistemic_distance=0)


@dataclass
class BatchComposer:
    params: Params = DEFAULT

    def compose(self, new: Sequence[Example], replay: Sequence[Example], general: Sequence[Example],
                social: Sequence[Example], recipe: Recipe, wiki: Wiki) -> Batch:
        if recipe.replay_fraction <= 0:
            raise InvariantViolation("I6", "every batch must include interleaved replay (fraction > 0)")
        if recipe.social_fraction >= self.params.social_train_fraction_hard:
            raise InvariantViolation("I3", "peer-derived material must stay strictly below one half")
        if not replay:
            raise InvariantViolation("I6", "replay pool is empty; cannot honour interleaved replay")
        rng = random.Random(recipe.seed)
        own = [e for e in new if eligible(e, wiki, self.params) and e.origin == "self"]
        if not own:
            raise ValueError("no eligible own examples: nothing to train")
        soc = [e for e in social if eligible(e, wiki, self.params) and e.origin == "social" and e.human_source]
        n_own = len(own)
        # Solve shares so that replay/general/social reach their target fractions of the total.
        rest = max(1e-9, 1.0 - recipe.replay_fraction - recipe.general_fraction - recipe.social_fraction)
        total = n_own / rest
        n_rep = max(1, round(total * recipe.replay_fraction))
        n_gen = round(total * recipe.general_fraction) if general else 0
        n_soc = min(len(soc), round(total * recipe.social_fraction))
        pick = lambda pool, n: [pool[rng.randrange(len(pool))] for _ in range(n)] if pool and n > 0 else []  # noqa: E731
        examples = own + pick(list(replay), n_rep) + pick(list(general), n_gen) + soc[:n_soc]
        batch = Batch(examples, recipe)
        if batch.social_share >= self.params.social_train_fraction_hard:
            raise InvariantViolation("I3", f"social share {batch.social_share:.2f} reached the hard cap")
        return batch


