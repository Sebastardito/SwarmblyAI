# Fresh test sets and the gate
# ---------------------------------------------------------------------------

@dataclass
class TestSetRegistry:
    __test__ = False  # not a pytest class
    used: dict[str, int] = field(default_factory=dict)  # test_id -> generation

    def fresh(self, wiki: Wiki, generation: int, exclude_examples: Iterable[str], k: int = 32, seed: int = 0) -> TestSet:
        """Questions from anchored claims not used as training examples in this generation."""
        excluded = set(exclude_examples)
        pool = [c for c in wiki.claims.values() if c.anchored and c.claim_id not in excluded]
        rng = random.Random(f"{seed}|{generation}")
        rng.shuffle(pool)
        qs = tuple((f"Q[{generation}]: {c.text[:80]}?", c.text) for c in pool[:k])
        oom = tuple(f"Q[{generation}]: unrelated-{i}-{seed}?" for i in range(max(4, k // 4)))
        tid = digest16({"g": generation, "q": qs, "seed": seed})
        if tid in self.used:
            raise InvariantViolation("I6", "test set already used by a previous generation")
        self.used[tid] = generation
        return TestSet(tid, generation, qs, oom)

    def assert_unused(self, test: TestSet, generation: int) -> None:
        g = self.used.get(test.test_id)
        if g is not None and g != generation:
            raise InvariantViolation("I6", f"test set {test.test_id} was used in generation {g}; reuse inflates the selected gain")


@dataclass
class Gate:
    params: Params = DEFAULT

    def choose(self, scored: Sequence[tuple[Adapter, GateScores]]) -> Adapter | None:
        passing = [(a, s) for a, s in scored if s.passes(self.params)]
        if not passing:
            return None
        return max(passing, key=lambda x: (x[1].wiki_gain, x[0].adapter_id))[0]


