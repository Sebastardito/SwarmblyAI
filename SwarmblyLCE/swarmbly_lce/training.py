class Trainer(Protocol):
    def train(self, base_model: str, batch: Batch, generation: int) -> Adapter:  # pragma: no cover - protocol
        ...


class Evaluator(Protocol):
    def evaluate(self, adapter: Adapter, test: TestSet, baseline: Adapter | None) -> GateScores:  # pragma: no cover
        ...


@dataclass
class MockTrainer:
    """Simulated trainer: an adapter's latent quality is a deterministic function
    of its recipe plus noise. SIMULATION ONLY — not evidence about real training."""

    sd_true: float = 10.0
    seed: int = 0

    def train(self, base_model: str, batch: Batch, generation: int) -> Adapter:
        r = batch.recipe
        rng = random.Random(f"{self.seed}|{r.recipe_id}|{generation}")
        q = 10.0 - 3.0 * abs(math.log2(max(r.rank, 1)) - 3.0) - 20.0 * abs(math.log10(r.lr) + 4.0) + rng.gauss(0, self.sd_true)
        q += 4.0 * (r.replay_fraction > 0)  # replay protects old behaviour
        aid = digest16({"b": base_model, "r": r.recipe_id, "g": generation, "ex": sorted(e.example_id for e in batch.examples)})
        return Adapter(aid, base_model, r, tuple(sorted({e.example_id for e in batch.examples})), init_from=base_model,
                       generation=generation, true_quality=q)


@dataclass
class MockEvaluator:
    """Noisy gate measurement of the latent quality.

    ``reliability`` is the correlation between measured and true gain; a
    *reused* test set adds a per-adapter bias that persists across
    generations, which is what makes reuse inflate the winner's apparent gain.
    """

    reliability: float = 0.5
    sd_true: float = 10.0
    seed: int = 0
    reuse_bias_sd: float = 0.0

    def evaluate(self, adapter: Adapter, test: TestSet, baseline: Adapter | None) -> GateScores:
        rng = random.Random(f"{self.seed}|{adapter.adapter_id}|{test.test_id}")
        rho = max(1e-6, min(1.0, self.reliability))
        noise_sd = self.sd_true * math.sqrt(1 / rho**2 - 1)
        base_q = baseline.true_quality if baseline and baseline.true_quality is not None else 0.0
        bias = random.Random(f"bias|{adapter.recipe.recipe_id}|{test.test_id}").gauss(0, self.reuse_bias_sd) if self.reuse_bias_sd else 0.0
        measured = (adapter.true_quality or 0.0) - base_q + rng.gauss(0, noise_sd) + bias
        return GateScores(wiki_gain=measured, general_loss=max(0.0, rng.gauss(1.0, 0.8)), abstain_rate=min(1.0, max(0.0, rng.gauss(0.9, 0.05))))


