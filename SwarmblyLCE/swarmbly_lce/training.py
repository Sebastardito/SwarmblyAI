"""Layer 2: training queue, adapter selection and forgetting (SPEC 7).

The adapter is a cache of *behaviour* (voice, register, terminology,
procedures). The rules implemented here:

* eligibility — only TRAINABLE claims or user corrections, distance ≤ 1, no
  stale dependency, no reference-only source (SPEC 7.1);
* batch composition — interleaved replay > 0 and peer-derived material strictly
  below one half (I3, I6);
* candidates — every candidate is initialised from the **base model**; nothing
  is inherited across generations but the recipe (I6);
* gate — improvement on memory-derived questions, bounded general loss and
  abstention outside memory, on a test set generated **for this generation**;
  reusing a test set is refused, because it inflates the observed gain of the
  selected candidate (Dwork et al., 2015);
* forgetting — an adapter trained on a stale example is retired and
  regenerated without it; approximate unlearning is never claimed (SPEC 7.8).

Trainers are pluggable. ``MockTrainer`` + ``MockEvaluator`` simulate adapters
with a latent true quality and a noisy gate so that selection bias can be
studied (H-C15); ``MLXLoRATrainer`` drives ``mlx_lm`` on Apple Silicon and is
experimental (not exercised in CI).
"""

